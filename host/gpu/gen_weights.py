"""Generate host/gpu/weights.h from the committed int8 model in model/weights/.

    python host/gpu/gen_weights.py

Reads the same whitespace-separated, row-major text files that host/bench_cpu.c loads
(W1 20x16, b1 1x16, W2 16x2, b2 1x2, X_test 5x20, z2_reference 5x2), checks their
shapes and ranges, and writes them out as C arrays so the CUDA program needs no file
I/O. Only uses the Python standard library. The output is deterministic, so
regenerating it on another machine gives an identical file.
"""
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
WEIGHTS = REPO / "model" / "weights"
OUT = Path(__file__).resolve().parent / "weights.h"

N_IN, N_HID, N_OUT, N_TEST = 20, 16, 2, 5
INT8 = (-128, 127)
INT32 = (-2**31, 2**31 - 1)


def load(name, rows, cols, value_range):
    lines = [line.split() for line in (WEIGHTS / name).read_text().splitlines() if line.strip()]
    values = [[int(v) for v in line] for line in lines]
    if len(values) != rows or any(len(row) != cols for row in values):
        raise SystemExit(f"{name}: expected {rows}x{cols}, got {len(values)} rows "
                         f"with {sorted({len(r) for r in values})} columns")
    lo, hi = value_range
    if any(not lo <= v <= hi for row in values for v in row):
        raise SystemExit(f"{name}: value outside [{lo}, {hi}]")
    return values


def c_array(ctype, name, values, dims):
    rows = ",\n".join("    {" + ", ".join(str(v) for v in row) + "}" for row in values)
    if len(dims) == 1:   # a single row stored as a 1-D array
        return f"static const {ctype} {name}[{dims[0]}] = {{" + ", ".join(str(v) for v in values[0]) + "};\n"
    return f"static const {ctype} {name}[{dims[0]}][{dims[1]}] = {{\n{rows}\n}};\n"


def main():
    W1 = load("W1.txt", N_IN, N_HID, INT8)
    b1 = load("b1.txt", 1, N_HID, INT8)
    W2 = load("W2.txt", N_HID, N_OUT, INT8)
    b2 = load("b2.txt", 1, N_OUT, INT8)
    X = load("X_test.txt", N_TEST, N_IN, INT8)
    Z2 = load("z2_reference.txt", N_TEST, N_OUT, INT32)

    text = (
        "// Generated by host/gpu/gen_weights.py from model/weights/*.txt. Do not edit by hand.\n"
        "// The frozen int8 model, the 5 test inputs and their bit-exact reference outputs.\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        f"static const int N_IN = {N_IN};     // inputs per example\n"
        f"static const int N_HID = {N_HID};    // hidden neurons\n"
        f"static const int N_OUT = {N_OUT};     // outputs (down, up)\n"
        f"static const int N_TEST = {N_TEST};    // test examples\n\n"
        + c_array("int8_t", "W1", W1, (N_IN, N_HID)) + "\n"
        + c_array("int8_t", "B1", b1, (N_HID,)) + "\n"
        + c_array("int8_t", "W2", W2, (N_HID, N_OUT)) + "\n"
        + c_array("int8_t", "B2", b2, (N_OUT,)) + "\n"
        + c_array("int8_t", "X_TEST", X, (N_TEST, N_IN)) + "\n"
        + c_array("int32_t", "Z2_REF", Z2, (N_TEST, N_OUT))
    )
    OUT.write_text(text, newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
