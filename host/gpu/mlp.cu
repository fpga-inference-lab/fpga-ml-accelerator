// CUDA version of the int8 20-16-2 MLP, with the same integer math as
// host/bench_cpu.c and the FPGA engines:
//
//   z1 = x @ W1 + b1*64 -> ReLU -> requant (z + 32) >> 6, cap 127 -> z2 = a1 @ W2 + b2*64
//
// One thread computes one whole inference, so a batch of N inputs is N threads.
// The weights live in __constant__ memory: every thread reads the same weight at the
// same time, which constant memory serves as a single broadcast.
//
//   nvcc -O3 -o mlp host/gpu/mlp.cu
//   ./mlp                       (run from the repo root; writes results/gpu_benchmark.json)
//
// The program first checks correctness and exits with status 1 on any mismatch:
//   - the 5 test examples, bit for bit against model/weights/z2_reference.txt
//   - a batch of 1M copies of those 5 examples, checking every output
//   - a batch of 1M random int8 inputs, checked against a CPU copy of bench_cpu.c's math
// Then it benchmarks, timing with cudaEvent (resolution about 0.5 us):
//   - batch-1 latency, kernel only and with host<->device copies
//   - a batch sweep from 1 to 1M inputs: kernel time, end-to-end time, throughput
// Host buffers are pinned (cudaMallocHost) so the copies run at full speed.
#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <vector>

#include <cuda_runtime.h>

#include "weights.h"   // generated by host/gpu/gen_weights.py from model/weights/

#define CHECK(call)                                                           \
    do {                                                                      \
        cudaError_t err_ = (call);                                            \
        if (err_ != cudaSuccess) {                                            \
            fprintf(stderr, "CUDA error: %s at %s:%d\n",                      \
                    cudaGetErrorString(err_), __FILE__, __LINE__);            \
            exit(1);                                                          \
        }                                                                     \
    } while (0)

static const int MAX_BATCH = 1 << 20;     // 1,048,576
static const int THREADS = 256;            // threads per block
static const int WARMUP = 20;
static const int LATENCY_REPS = 10000;     // batch-1 latency
static const int SWEEP_REPS = 500;         // each batch size in the sweep
static const int SWEEP[] = {1, 16, 256, 4096, 65536, 1 << 20};

__constant__ int8_t c_W1[N_IN][N_HID];
__constant__ int8_t c_B1[N_HID];
__constant__ int8_t c_W2[N_HID][N_OUT];
__constant__ int8_t c_B2[N_OUT];

__global__ void mlp_kernel(const int8_t *x, int32_t *z2, int n) {
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i >= n)
        return;

    int8_t xi[N_IN];
    for (int k = 0; k < N_IN; k++)
        xi[k] = x[(size_t)i * N_IN + k];

    int8_t a1[N_HID];
    for (int j = 0; j < N_HID; j++) {
        int32_t acc = c_B1[j] * 64;
        for (int k = 0; k < N_IN; k++)
            acc += xi[k] * c_W1[k][j];
        if (acc < 0) acc = 0;
        acc = (acc + 32) >> 6;
        a1[j] = acc > 127 ? 127 : acc;
    }
    for (int o = 0; o < N_OUT; o++) {
        int32_t acc = c_B2[o] * 64;
        for (int j = 0; j < N_HID; j++)
            acc += a1[j] * c_W2[j][o];
        z2[(size_t)i * N_OUT + o] = acc;
    }
}

// CPU copy of infer() in host/bench_cpu.c, used to check the random-input batch
static void infer_cpu(const int8_t x[N_IN], int32_t z2[N_OUT]) {
    int8_t a1[N_HID];
    for (int j = 0; j < N_HID; j++) {
        int32_t acc = B1[j] * 64;
        for (int k = 0; k < N_IN; k++)
            acc += x[k] * W1[k][j];
        if (acc < 0) acc = 0;
        acc = (acc + 32) >> 6;
        a1[j] = acc > 127 ? 127 : acc;
    }
    for (int o = 0; o < N_OUT; o++) {
        int32_t acc = B2[o] * 64;
        for (int j = 0; j < N_HID; j++)
            acc += a1[j] * W2[j][o];
        z2[o] = acc;
    }
}

static void launch(const int8_t *d_x, int32_t *d_z2, int n) {
    int blocks = (n + THREADS - 1) / THREADS;
    mlp_kernel<<<blocks, THREADS>>>(d_x, d_z2, n);
}

// input i is test example i % 5
static void fill_replicated(int8_t *h_x, int n) {
    for (int i = 0; i < n; i++)
        for (int k = 0; k < N_IN; k++)
            h_x[(size_t)i * N_IN + k] = X_TEST[i % N_TEST][k];
}

static long count_replicated_mismatches(const int32_t *h_z2, int n) {
    long bad = 0;
    for (int i = 0; i < n; i++)
        for (int o = 0; o < N_OUT; o++)
            if (h_z2[(size_t)i * N_OUT + o] != Z2_REF[i % N_TEST][o])
                bad++;
    return bad;
}

// run n inputs through the GPU once (copy in, kernel, copy out)
static void run_once(const int8_t *h_x, int32_t *h_z2, int8_t *d_x, int32_t *d_z2, int n) {
    CHECK(cudaMemcpy(d_x, h_x, (size_t)n * N_IN, cudaMemcpyHostToDevice));
    launch(d_x, d_z2, n);
    CHECK(cudaGetLastError());
    CHECK(cudaMemcpy(h_z2, d_z2, (size_t)n * N_OUT * sizeof(int32_t), cudaMemcpyDeviceToHost));
}

struct Stats {
    double min_us, median_us, p99_us, max_us;
};

// percentile index convention matches host/bench_cpu.c: p/100 * (n - 1)
static Stats summarize(std::vector<float> ms) {
    std::sort(ms.begin(), ms.end());
    size_t n = ms.size();
    Stats s;
    s.min_us = ms[0] * 1000.0;
    s.median_us = ms[(size_t)(0.50 * (n - 1))] * 1000.0;
    s.p99_us = ms[(size_t)(0.99 * (n - 1))] * 1000.0;
    s.max_us = ms[n - 1] * 1000.0;
    return s;
}

struct Result {
    int batch, reps;
    Stats kernel, e2e;
    long mismatches;
};

// Times one batch size. h_x must already hold n replicated test inputs.
//   kernel: cudaEvent around the kernel launch only (input already on the GPU)
//   e2e:    cudaEvent around copy in + kernel + copy out
static Result bench(int n, int reps, const int8_t *h_x, int32_t *h_z2, int8_t *d_x, int32_t *d_z2) {
    cudaEvent_t start, stop;
    CHECK(cudaEventCreate(&start));
    CHECK(cudaEventCreate(&stop));
    size_t in_bytes = (size_t)n * N_IN;
    size_t out_bytes = (size_t)n * N_OUT * sizeof(int32_t);
    std::vector<float> kernel_ms(reps), e2e_ms(reps);

    CHECK(cudaMemcpy(d_x, h_x, in_bytes, cudaMemcpyHostToDevice));
    for (int r = 0; r < WARMUP; r++)
        launch(d_x, d_z2, n);
    CHECK(cudaGetLastError());
    CHECK(cudaDeviceSynchronize());
    for (int r = 0; r < reps; r++) {
        CHECK(cudaEventRecord(start));
        launch(d_x, d_z2, n);
        CHECK(cudaEventRecord(stop));
        CHECK(cudaEventSynchronize(stop));
        CHECK(cudaEventElapsedTime(&kernel_ms[r], start, stop));
    }
    CHECK(cudaGetLastError());

    for (int r = 0; r < WARMUP + reps; r++) {
        CHECK(cudaEventRecord(start));
        CHECK(cudaMemcpyAsync(d_x, h_x, in_bytes, cudaMemcpyHostToDevice));
        launch(d_x, d_z2, n);
        CHECK(cudaMemcpyAsync(h_z2, d_z2, out_bytes, cudaMemcpyDeviceToHost));
        CHECK(cudaEventRecord(stop));
        CHECK(cudaEventSynchronize(stop));
        if (r >= WARMUP)
            CHECK(cudaEventElapsedTime(&e2e_ms[r - WARMUP], start, stop));
    }
    CHECK(cudaGetLastError());

    Result res;
    res.batch = n;
    res.reps = reps;
    res.kernel = summarize(kernel_ms);
    res.e2e = summarize(e2e_ms);
    res.mismatches = count_replicated_mismatches(h_z2, n);   // outputs of the last e2e run
    CHECK(cudaEventDestroy(start));
    CHECK(cudaEventDestroy(stop));
    return res;
}

static double per_second(int n, double us) { return n / (us * 1e-6); }

static void print_stats_json(FILE *f, const char *name, const Stats &s, const char *end) {
    fprintf(f, "\"%s\": {\"min_us\": %.3f, \"median_us\": %.3f, \"p99_us\": %.3f, \"max_us\": %.3f}%s",
            name, s.min_us, s.median_us, s.p99_us, s.max_us, end);
}

int main(int argc, char **argv) {
    const char *json_path = argc > 1 ? argv[1] : "results/gpu_benchmark.json";

    cudaDeviceProp prop;
    CHECK(cudaGetDeviceProperties(&prop, 0));
    int runtime_ver = 0, driver_ver = 0;
    CHECK(cudaRuntimeGetVersion(&runtime_ver));
    CHECK(cudaDriverGetVersion(&driver_ver));
    printf("GPU: %s (compute capability %d.%d, %d SMs), CUDA runtime %d, driver %d\n\n",
           prop.name, prop.major, prop.minor, prop.multiProcessorCount, runtime_ver, driver_ver);

    CHECK(cudaMemcpyToSymbol(c_W1, W1, sizeof(W1)));
    CHECK(cudaMemcpyToSymbol(c_B1, B1, sizeof(B1)));
    CHECK(cudaMemcpyToSymbol(c_W2, W2, sizeof(W2)));
    CHECK(cudaMemcpyToSymbol(c_B2, B2, sizeof(B2)));

    int8_t *h_x, *d_x;
    int32_t *h_z2, *d_z2;
    CHECK(cudaMallocHost(&h_x, (size_t)MAX_BATCH * N_IN));
    CHECK(cudaMallocHost(&h_z2, (size_t)MAX_BATCH * N_OUT * sizeof(int32_t)));
    CHECK(cudaMalloc(&d_x, (size_t)MAX_BATCH * N_IN));
    CHECK(cudaMalloc(&d_z2, (size_t)MAX_BATCH * N_OUT * sizeof(int32_t)));

    // ---------------------------------------------------------------- correctness
    bool ok = true;

    fill_replicated(h_x, N_TEST);
    run_once(h_x, h_z2, d_x, d_z2, N_TEST);
    for (int m = 0; m < N_TEST; m++) {
        bool match = h_z2[m * N_OUT] == Z2_REF[m][0] && h_z2[m * N_OUT + 1] == Z2_REF[m][1];
        printf("example %d: z2 = %d %d  expected %d %d  %s\n", m, h_z2[m * N_OUT], h_z2[m * N_OUT + 1],
               Z2_REF[m][0], Z2_REF[m][1], match ? "OK" : "MISMATCH");
        ok = ok && match;
    }
    printf("5 test examples: %s\n", ok ? "PASS" : "FAIL");

    fill_replicated(h_x, MAX_BATCH);
    run_once(h_x, h_z2, d_x, d_z2, MAX_BATCH);
    long bad = count_replicated_mismatches(h_z2, MAX_BATCH);
    printf("replicated batch of %d (test examples repeated): %s (%ld mismatched outputs)\n",
           MAX_BATCH, bad == 0 ? "PASS" : "FAIL", bad);
    ok = ok && bad == 0;

    srand(1);
    for (size_t i = 0; i < (size_t)MAX_BATCH * N_IN; i++)
        h_x[i] = (int8_t)(rand() % 256 - 128);
    run_once(h_x, h_z2, d_x, d_z2, MAX_BATCH);
    bad = 0;
    for (int i = 0; i < MAX_BATCH; i++) {
        int32_t expect[N_OUT];
        infer_cpu(&h_x[(size_t)i * N_IN], expect);
        for (int o = 0; o < N_OUT; o++)
            if (h_z2[(size_t)i * N_OUT + o] != expect[o])
                bad++;
    }
    printf("random batch of %d (checked against the CPU reference): %s (%ld mismatched outputs)\n\n",
           MAX_BATCH, bad == 0 ? "PASS" : "FAIL", bad);
    ok = ok && bad == 0;

    if (!ok) {
        printf("CORRECTNESS FAIL: not benchmarking\n");
        return 1;
    }

    // ---------------------------------------------------------------- benchmark
    fill_replicated(h_x, MAX_BATCH);   // a prefix of n inputs is also replicated

    Result lat = bench(1, LATENCY_REPS, h_x, h_z2, d_x, d_z2);
    printf("Batch-1 latency (%d reps, cudaEvent):\n", LATENCY_REPS);
    printf("| | median | p99 | min | max |\n|---|---:|---:|---:|---:|\n");
    printf("| kernel only | %.2f us | %.2f us | %.2f us | %.2f us |\n",
           lat.kernel.median_us, lat.kernel.p99_us, lat.kernel.min_us, lat.kernel.max_us);
    printf("| with host<->device copies | %.2f us | %.2f us | %.2f us | %.2f us |\n\n",
           lat.e2e.median_us, lat.e2e.p99_us, lat.e2e.min_us, lat.e2e.max_us);

    std::vector<Result> sweep;
    for (int n : SWEEP)
        sweep.push_back(bench(n, SWEEP_REPS, h_x, h_z2, d_x, d_z2));

    printf("Batch sweep (%d reps each, cudaEvent; throughput uses the median):\n", SWEEP_REPS);
    printf("| batch | kernel median | kernel p99 | end-to-end median | end-to-end p99 "
           "| kernel throughput | end-to-end throughput |\n");
    printf("|---:|---:|---:|---:|---:|---:|---:|\n");
    for (const Result &r : sweep)
        printf("| %d | %.2f us | %.2f us | %.2f us | %.2f us | %.4g inf/s | %.4g inf/s |\n",
               r.batch, r.kernel.median_us, r.kernel.p99_us, r.e2e.median_us, r.e2e.p99_us,
               per_second(r.batch, r.kernel.median_us), per_second(r.batch, r.e2e.median_us));

    long sweep_bad = lat.mismatches;
    for (const Result &r : sweep)
        sweep_bad += r.mismatches;
    printf("\nbenchmark outputs checked: %s (%ld mismatched outputs)\n",
           sweep_bad == 0 ? "PASS" : "FAIL", sweep_bad);

    FILE *f = fopen(json_path, "w");
    if (!f) {
        fprintf(stderr, "can't write %s (run from the repo root)\n", json_path);
        return 1;
    }
    fprintf(f, "{\n  \"gpu\": \"%s\",\n  \"compute_capability\": \"%d.%d\",\n  \"sm_count\": %d,\n",
            prop.name, prop.major, prop.minor, prop.multiProcessorCount);
    fprintf(f, "  \"cuda_runtime\": %d,\n  \"cuda_driver\": %d,\n", runtime_ver, driver_ver);
    fprintf(f, "  \"method\": \"one thread per inference, %d threads per block, weights in __constant__, "
               "pinned host memory, cudaEvent timing, %d warmup runs; end_to_end = host->device copy + "
               "kernel + device->host copy\",\n", THREADS, WARMUP);
    fprintf(f, "  \"correctness\": {\"test_examples\": \"PASS\", \"replicated_batch\": %d, "
               "\"random_batch\": %d, \"benchmark_outputs_mismatched\": %ld},\n",
            MAX_BATCH, MAX_BATCH, sweep_bad);
    fprintf(f, "  \"batch1_latency\": {\"reps\": %d, ", lat.reps);
    print_stats_json(f, "kernel", lat.kernel, ", ");
    print_stats_json(f, "end_to_end", lat.e2e, "},\n");
    fprintf(f, "  \"sweep\": [\n");
    for (size_t s = 0; s < sweep.size(); s++) {
        const Result &r = sweep[s];
        fprintf(f, "    {\"batch\": %d, \"reps\": %d, ", r.batch, r.reps);
        print_stats_json(f, "kernel", r.kernel, ", ");
        print_stats_json(f, "end_to_end", r.e2e, ", ");
        fprintf(f, "\"kernel_inferences_per_s\": %.6g, \"end_to_end_inferences_per_s\": %.6g}%s\n",
                per_second(r.batch, r.kernel.median_us), per_second(r.batch, r.e2e.median_us),
                s + 1 < sweep.size() ? "," : "");
    }
    fprintf(f, "  ]\n}\n");
    fclose(f);
    printf("wrote %s\n", json_path);

    CHECK(cudaFreeHost(h_x));
    CHECK(cudaFreeHost(h_z2));
    CHECK(cudaFree(d_x));
    CHECK(cudaFree(d_z2));
    return sweep_bad == 0 ? 0 : 1;
}
